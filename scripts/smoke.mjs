  await page.waitForTimeout(150);
  await assertPixels(output.locator('.projection-canvas'), 'Restored projector output');
  await page.getByRole('button', { name: 'Manage output', exact: true }).click();
  await page.getByRole('button', { name: 'Calibration grid', exact: false }).click();
  await page.waitForTimeout(150);
  await output.screenshot({ path: path.join(artifacts, 'luma-calibration.png') });

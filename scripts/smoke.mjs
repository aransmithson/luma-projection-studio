  await page.getByRole('button', { name: 'Show Polygon 8', exact: true }).click();
  await expect(page.locator('.surface-outline')).toHaveCount(8);
  console.log('PASS: seasonal filters, effect assignment, search, favourites, lock and visibility');

  await page.getByLabel('Project name', { exact: true }).fill('Desktop smoke project');
  await page.getByLabel('Project name', { exact: true }).press('Enter');

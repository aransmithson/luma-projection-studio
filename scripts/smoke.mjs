  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await output.bringToFront();
  await output.keyboard.press('f');
  await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(win => win.getTitle().includes('Projector output'))?.isFullScreen())).toBe(true);
  await output.keyboard.press('f');
  await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(win => win.getTitle().includes('Projector output'))?.isFullScreen())).toBe(false);
